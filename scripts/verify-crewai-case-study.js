import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import puppeteer from 'puppeteer';

const base = process.env.PORTFOLIO_TEST_URL || 'http://127.0.0.1:4178';
const output = '/tmp/crewai-case-study-qa';
const pdfPath = '/documents/crewai-revenueops-executive-summary.pdf';
const hash = data => createHash('sha256').update(data).digest('hex');
await fs.mkdir(output, { recursive: true });
const browser = await puppeteer.launch({ headless: true });
const errors = [], results = [];
try {
  const page = await browser.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 1024, height: 900 }, { width: 768, height: 1000 }, { width: 390, height: 844 }, { width: 320, height: 700 }]) {
    await page.setViewport(viewport);
    await page.goto(`${base}/projects/crewai-revenueops`, { waitUntil: 'networkidle0' });
    await page.waitForSelector('.revenueops-project .project-hero');
    await page.waitForFunction(() => Number(document.querySelector('.project-hero-content').style.getPropertyValue('--scroll-load-opacity')) >= 1);
    assert.match(await page.$eval('h1', e => e.textContent), /CrewAI RevenueOps.*Intelligence/);
    assert.equal(await page.$eval('[data-project-back]', e => e.getAttribute('href')), '/');
    assert(await page.$eval('.revenueops-hero', e => e.getBoundingClientRect().height <= innerHeight + 1), `Hero exceeds viewport at ${viewport.width}`);
    assert(await page.$eval('.revenueops-hero-inner', e => e.getBoundingClientRect().bottom <= innerHeight + 1), `Hero content clipped at ${viewport.width}`);
    assert.equal(await page.$eval('.revenueops-actions a', e => e.getAttribute('href')), 'https://github.com/keenosmith-del/crewai-revenueops');
    assert.equal(await page.$$eval('.revenueops-actions :is(a,button)', els => els.length), 2);
    assert.equal(await page.$('.revenueops-hero a[href$=".pdf"]'), null);
    assert.equal(await page.$eval('.revenueops-problem a', e => e.getAttribute('href')), pdfPath);
    assert(await page.$$eval('article > header, article > section', sections => sections.every(section => section.querySelectorAll('.revenueops-button').length <= 2)));
    assert(await page.$eval('.revenueops-actions button', e => e.disabled));
    assert.equal(await page.$$eval('.revenueops-journey-grid > li', els => els.length), 6);
    assert.equal(await page.$$eval('.revenueops-specialists > div', els => els.length), 4);
    assert.deepEqual(await page.$$eval('.revenueops-comparison tbody tr', rows => rows.map(row => [...row.querySelectorAll('td')].map(cell => cell.textContent))), [['0/4', '1/4'], ['1/7', '4/7']]);
    assert.match(await page.$eval('.revenueops-regression', e => e.textContent), /13\/13/);
    assert.match(await page.$eval('.revenueops-evaluation-observations', e => e.textContent), /24\/24.*9\/11.*0/s);
    assert.match(await page.$eval('.revenueops-release-details', e => e.textContent), /Staging and production deployment have not been performed/);
    assert.equal(await page.$$eval('.revenueops-project :is(video, iframe, article img)', els => els.filter(e => !e.closest('.revenueops-actions')).length), 0);
    assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), `Page overflow ${viewport.width}`);
    await page.screenshot({ path: `${output}/hero-${viewport.width}.png` });
    const sections = await page.$$('article > section');
    for (let i = 0; i < sections.length; i++) {
      await sections[i].evaluate(e => window.scrollTo({ top: e.getBoundingClientRect().top + scrollY - 60, behavior: 'instant' }));
      await page.waitForFunction(index => Number(getComputedStyle(document.querySelectorAll('article > section')[index]).opacity) > .99, {}, i);
      const clipped = await sections[i].evaluate(e => [...e.querySelectorAll('h2,h3,p,li,td,th,button,a')].filter(node => { const r = node.getBoundingClientRect(); return r.width && (r.left < -1 || r.right > innerWidth + 1); }).map(node => node.textContent));
      assert.deepEqual(clipped, [], `Clipped content ${viewport.width} section ${i}`);
      if ([1440, 390].includes(viewport.width)) await sections[i].screenshot({ path: `${output}/section-${i}-${viewport.width}.png` });
    }
    const trigger = await page.$('.revenueops-tech-trigger');
    await trigger.evaluate(e => e.scrollIntoView({ block: 'center', behavior: 'instant' }));
    await trigger.click();
    await page.waitForSelector('[role="dialog"]');
    assert(await page.$eval('[role="dialog"]', e => e.contains(document.activeElement)));
    assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden');
    assert.equal(await page.$$eval('.project-modal-group', els => els.length), 6);
    assert(await page.$eval('.project-modal', e => { const r = e.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight && e.scrollWidth === e.clientWidth; }));
    assert(await page.$eval('article', e => e.inert));
    await page.keyboard.press('Tab');
    assert(await page.$eval('.project-modal-close', e => e === document.activeElement));
    await page.keyboard.press('Tab');
    assert(await page.$eval('.project-modal-close', e => e === document.activeElement));
    await page.keyboard.down('Shift'); await page.keyboard.press('Tab'); await page.keyboard.up('Shift');
    assert(await page.$eval('.project-modal-close', e => e === document.activeElement));
    await page.screenshot({ path: `${output}/modal-${viewport.width}.png` });
    await page.keyboard.press('Escape');
    assert.equal(await page.$('[role="dialog"]'), null);
    assert(await trigger.evaluate(e => e === document.activeElement));
    assert.equal(await page.evaluate(() => document.body.style.overflow), '');
    assert(!await page.$eval('article', e => e.inert));
    await trigger.click(); await page.waitForSelector('[role="dialog"]');
    await page.click('.project-modal-close');
    assert.equal(await page.$('[role="dialog"]'), null);
    await trigger.click(); await page.waitForSelector('[role="dialog"]');
    await page.mouse.click(2, 2);
    assert.equal(await page.$('[role="dialog"]'), null);
    await page.$eval('.revenueops-footer', e => e.scrollIntoView({ behavior: 'instant' }));
    await page.waitForFunction(() => !document.querySelector('.revenueops-floating-top'));
    await page.click('.revenueops-footer-top');
    await page.waitForFunction(() => scrollY < 2);
    results.push({ ...viewport, hero: 'fits', sections: sections.length, overflow: false, modal: 'keyboard/close/focus/scroll passed' });
  }
  // Read the HTTP asset itself; Chrome navigation exposes its PDF viewer HTML.
  const pdfResponse = await fetch(base + pdfPath);
  assert.equal(pdfResponse.status, 200);
  assert.match(pdfResponse.headers.get('content-type'), /application\/pdf/);
  const pdf = Buffer.from(await pdfResponse.arrayBuffer());
  assert.equal(pdf.subarray(0, 5).toString(), '%PDF-');
  assert.equal(hash(pdf), hash(await fs.readFile(`public${pdfPath}`)));
  assert.equal(hash(pdf), 'a7e876b5f28a2da1754b3d2c460d250cfeed12e80336eb0b4a0f6b7b54f8bd45');
  await page.goto(base + '/explore/projects/crewai-revenueops', { waitUntil: 'networkidle0' });
  assert(await page.$('.revenueops-project'));
  const filtered = '/explore?tab=projects&q=CrewAI&category=ai';
  await page.goto(base + filtered, { waitUntil: 'networkidle0' });
  assert.equal(await page.$$eval('[data-explore-id="crewai-revenueops"]', els => els.length), 1);
  assert.equal(await page.$eval('[data-explore-id="crewai-revenueops"]', e => e.getAttribute('href')), '/projects/crewai-revenueops');
  await page.click('[data-explore-id="crewai-revenueops"]');
  await page.waitForSelector('.revenueops-project');
  assert.equal(await page.$eval('[data-project-back]', e => e.getAttribute('href')), filtered);
  await page.click('[data-project-back]'); await page.waitForSelector('.explore-project');
  assert.equal(new URL(page.url()).pathname + new URL(page.url()).search, filtered);
  await page.click('[data-explore-id="crewai-revenueops"]'); await page.waitForSelector('.revenueops-project');
  await page.reload({ waitUntil: 'networkidle0' });
  assert.equal(await page.$eval('[data-project-back]', e => e.getAttribute('href')), '/');
  await page.goto(base + '/explore?tab=skills&q=CrewAI', { waitUntil: 'networkidle0' });
  await page.click('[data-explore-id="crewai"]'); await page.waitForSelector('dialog[open]');
  assert(await page.$('dialog a[href="/projects/crewai-revenueops"]'));
  await page.keyboard.press('Escape');
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
  await page.setViewport({ width: 390, height: 844 });
  await page.goto(base + '/projects/crewai-revenueops', { waitUntil: 'networkidle0' });
  assert.equal(await page.$eval('.project-hero-content', e => getComputedStyle(e).opacity), '1');
  assert.equal(await page.$eval('.revenueops-button', e => getComputedStyle(e).transitionDuration), '0s');
  await page.screenshot({ path: `${output}/full-mobile-reduced-motion.png`, fullPage: true });
  assert.deepEqual(errors, []);
  await fs.writeFile(`${output}/results.json`, JSON.stringify({ results, pdf: 'served supplied PDF unchanged', oldRoute: 'passed', exploreOrigin: 'passed', refreshFallback: 'passed', skillLink: 'passed', reducedMotion: 'passed', errors }, null, 2));
  console.log('PASS: CrewAI canonical/legacy routes, 5 responsive sizes, all section bounds, honest evaluation figures, supplied PDF hash, modal keyboard/focus/scroll/close, Explore filters/skill link, footer/top and reduced motion.');
} finally {
  await browser.close();
}
